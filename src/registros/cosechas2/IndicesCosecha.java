package registros.cosechas2;

public class IndicesCosecha {
    private int indiceCamp;
    private int indiceProd;
    private int indiceAnio;

    public int getIndiceCamp() {
        return indiceCamp;
    }

    public void setIndiceCamp(int indiceCamp) {
        this.indiceCamp = indiceCamp;
    }

    public int getIndiceProd() {
        return indiceProd;
    }

    public void setIndiceProd(int indiceProd) {
        this.indiceProd = indiceProd;
    }

    public int getIndiceAnio() {
        return indiceAnio;
    }

    public void setIndiceAnio(int indiceAnio) {
        this.indiceAnio = indiceAnio;
    }
}
